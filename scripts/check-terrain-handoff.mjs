import assert from 'node:assert/strict';
import { bandHandoff, captureMotion, restoreMotion, nativePortalHandoff, startsDescentRun } from '../src/pov/descent/terrainHandoff.js';
import { createDescentRunner, runSnapshot } from '../src/pov/descent/switch.js';
const fold = { sourceMinX: -4608, sourceWidth: 9216, thickness: 48 };
const levels = [0, 1, 2].map((i) => ({ key: `r${i}`, name: `Band ${i}`, fold, sourceRegion: { core: [1024 + i * 256, 1280 + i * 256] }, nativePortals: [], toWorld: ([x,y,d]) => [x + 5000, 1024 + i * 256 + 288 - y, d + 2000] }));
assert.equal(startsDescentRun(null,levels[1],levels),true,'initial band 01 starts a run');
assert.equal(startsDescentRun(levels[1],levels[0],levels),false,'upward seam into band 00 cannot reset purse');
const down = [-677,1280.125,3.25];
assert.deepEqual(bandHandoff(levels, levels[0], down).source, down);
assert.equal(bandHandoff(levels, levels[0], down).next, levels[1]);
assert.equal(bandHandoff(levels, levels[1], [-677,1279.75,3.25]).next, levels[0]);
assert.equal(bandHandoff(levels, levels[0], [-4609,1280,0]), null);
assert.equal(bandHandoff(levels, levels[0], [-677,1280,24]), null);
assert.equal(bandHandoff(levels, levels[0], [-677,1550,0]), null);
const player = { health: 67, shield: 4, vel: { x:1,y:-2,z:3,set(x,y,z) { Object.assign(this,{x,y,z}); } } };
const motion = captureMotion(player, { yaw: 1.4, pitch: -.3 });
let look;
restoreMotion(player, (yaw,pitch) => { look = [yaw,pitch]; }, motion);
assert.deepEqual(look,[1.4,-.3]);
assert.deepEqual([player.vel.x,player.vel.y,player.vel.z],[1,-2,3]);
const wands = { wands: [{id:'starter'}], bag: ['spell'], potions: [{material:'WATER',cells:[1,2]}] };
const snapshot = () => runSnapshot({player,gold:19,wands});
const before = snapshot(), calls = [];
const runner = createDescentRunner({ levels, emit:()=>{}, wait:async()=>{}, snapshot,
  loadScene:async(key,at) => { calls.push(['load',key,at]); }, enterAt:async(at) => calls.push(['enter',at]), loadId:()=>2 });
await runner.frame({key:'r0',source:down,live:true,load:1});
assert.deepEqual(calls,[['load','r1',levels[1].toWorld(down)],['enter',levels[1].toWorld(down)]]);
assert.deepEqual(snapshot(),before);
await runner.frame({key:'r1',source:[-677,1279.75,3.25],live:true,load:2});
assert.equal(calls[2][1],'r0');
assert.equal(nativePortalHandoff(levels,levels[0],down),null);
const portal = {id:'fixture-native',source:[-677,1100],halfSize:[15,15],target:[-500,1600],enabled:true};
levels[0].nativePortals=[portal];
assert.deepEqual(nativePortalHandoff(levels,levels[0],[-677,1100,3.25]).source,[-500,1600,3.25]);
assert.equal(nativePortalHandoff(levels,levels[0],[-677,1100,3.25]).next,levels[2]);
assert.equal(nativePortalHandoff(levels,levels[0],[-700,1100,3.25]),null);
await runner.frame({key:'r0',source:[-677,1100,3.25],live:true,load:3});
assert.equal(calls[4][1],'r2');
assert.deepEqual(calls[4][2],levels[2].toWorld([-500,1600,3.25]));
assert.deepEqual(snapshot(),before,'native portal preserves inventory, health, shield and potions');
console.log('Terrain handoffs: both source-coordinate directions, domain guards, arrival-before-load, motion and run-state preservation passed');
