// The killfeed's icons (src/pov/killicons.js), baked from game-icons.net: about 4,000
// silhouette icons by Lorc, Delapouite, Skoll and others under CC BY 3.0
// (https://game-icons.net, https://github.com/game-icons/icons). They stand in for
// Half-Life 2's kill icon font, which is Valve's and can't be copied; like it they
// are one flat shape each, which the killfeed draws in GMod's kill-icon orange.
//
// Each icon is fetched from the repo at a pinned commit, its black background square
// dropped and its numbers cut to one decimal (a 512-unit box drawn ~32 px tall: a
// tenth of a unit is invisible). Rerun after changing ICONS.
// usage: node tools/killicons.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const REPO = 'https://raw.githubusercontent.com/game-icons/icons';
const COMMIT = '82d948812bfe3f269ef8f731dcdb07b08160edc4';
const OUT = join(new URL('..', import.meta.url).pathname, 'src/pov/killicons.js');
const AUTHORS = { lorc: 'Lorc', delapouite: 'Delapouite', skoll: 'Skoll', sbed: 'Sbed', 'carl-olsen': 'Carl Olsen' };

// icon key (a tool key from tools/catalog.js, or a kind of death) → '<author>/<name>' in the repo
const ICONS = {
  default: 'lorc/skull-crossed-bones',   // GMod's 'default' kill icon is a skull: suicides and unknown deaths
  // the tools (catalog.js keys)
  SHOVEL: 'skoll/trench-spade',
  PICKAXE: 'delapouite/war-pick',
  AXE: 'lorc/wood-axe',
  KNIFE: 'skoll/butterfly-knife',   // the Spy's knife (TF2)
  TROWEL: 'delapouite/trowel',
  BUCKET: 'delapouite/full-metal-bucket',
  FLASK: 'lorc/round-bottom-flask',
  GUN: 'skoll/glock',
  SMG: 'skoll/mp5k',
  SNIPER: 'skoll/lee-enfield',
  LASER: 'lorc/ray-gun',
  BOMB: 'lorc/unlit-bomb',
  ROCKET: 'lorc/rocket',
  BURROWER: 'delapouite/drill',
  PHYSGUN: 'lorc/magnet',
  BLOWTORCH: 'delapouite/flamethrower',
  POGO: 'delapouite/bouncing-spring',
  TORCH: 'delapouite/torch',
  LANTERN: 'lorc/lantern-flame',
  HOOK: 'lorc/grapple',
  WAND: 'lorc/fairy-wand',
  // blows that aren't a held tool
  backstab: 'lorc/backstab',
  kick: 'lorc/boot-kick',
  worm: 'lorc/worm-mouth',
  jeep: 'skoll/jeep',
  hoverbike: 'delapouite/aero-bike',
  shot: 'lorc/bullets',
  // the world's
  explosion: 'lorc/bright-explosion',
  fire: 'carl-olsen/flame',
  lava: 'sbed/lava',
  acid: 'sbed/acid',
  cold: 'lorc/snowflake-2',
  drowned: 'lorc/drowning',
  buried: 'lorc/tombstone',
  fall: 'sbed/falling',
  impact: 'lorc/impact-point',
  shock: 'sbed/electric',
  poison: 'lorc/poison-gas',
};

const BACKGROUND = '<path d="M0 0h512v512H0z"/>';
const PATH = /<path[^>]*\bd="([^"]+)"/g;
const tenths = (d) => d.replace(/(\.\d)\d+/g, '$1');

const out = {};
const used = new Set();
for (const [key, src] of Object.entries(ICONS)) {
  const res = await fetch(`${REPO}/${COMMIT}/${src}.svg`);
  if (!res.ok) throw new Error(`${src}: HTTP ${res.status}`);
  const svg = (await res.text()).replace(BACKGROUND, '');
  const paths = [...svg.matchAll(PATH)].map((m) => tenths(m[1]));
  if (!paths.length) throw new Error(`${src}: no path`);
  const author = src.split('/')[0];
  if (!AUTHORS[author]) throw new Error(`${src}: add its author to AUTHORS`);
  used.add(AUTHORS[author]);
  out[key] = { d: paths.join(' '), by: AUTHORS[author], src };
}

const by = [...used].sort();
const credit = `Kill icons by ${by.slice(0, -1).join(', ')} and ${by.at(-1)}, from game-icons.net (CC BY 3.0, recoloured)`;
const body = Object.entries(out).map(([k, v]) => `  ${/^[A-Za-z_]\w*$/.test(k) ? k : `'${k}'`}: { by: '${v.by}', src: '${v.src}', d: '${v.d}' },`).join('\n');
writeFileSync(OUT, `// Generated by tools/killicons.mjs: don't edit, rerun it.
// game-icons.net icons (https://game-icons.net, CC BY 3.0: https://creativecommons.org/licenses/by/3.0/),
// commit ${COMMIT} of github.com/game-icons/icons. Changes: the black background
// square removed, numbers cut to one decimal, drawn in one colour.
// Each: d (path data in a 512-unit box), by (its author), src (its file in the repo).
export const KILLICON_BOX = 512;
export const KILLICON_CREDIT = '${credit}';
export const KILLICONS = {
${body}
};
`);
console.log(`${Object.keys(out).length} icons → ${OUT} (${(body.length / 1024).toFixed(1)} KB)\n${credit}`);
