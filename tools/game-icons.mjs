// Bakes icons from game-icons.net into a small JS module: about 4,000 silhouette icons
// by Lorc, Delapouite, Skoll and others under CC BY 3.0 (https://game-icons.net,
// https://github.com/game-icons/icons). Each icon is one flat shape, drawn in one
// colour by whoever uses it (GMod's kill-icon orange in the killfeed).
//
// Each icon is fetched from the repo at a pinned commit, its black background square
// dropped and its numbers cut to one decimal (a 512-unit box drawn tens of px tall: a
// tenth of a unit is invisible). The module exports <PREFIX>_BOX, <PREFIX>_CREDIT
// (the attribution CC BY asks for) and <PREFIX>S { key: { d, by, src } }.
//
// A set of icons is a small script that calls bakeIcons (tools/killicons.mjs is one).
// To pick icons: search the repo's tree (gh api repos/game-icons/icons/git/trees/<COMMIT>?recursive=1),
// fetch candidates with `/usr/bin/curl -o` (rtk truncates curl's stdout) and look at them
// on a contact sheet (rsvg-convert, then magick montage).
import { writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

export const REPO = 'https://raw.githubusercontent.com/game-icons/icons';
export const COMMIT = '82d948812bfe3f269ef8f731dcdb07b08160edc4';
const ROOT = join(new URL('..', import.meta.url).pathname);
const BACKGROUND = '<path d="M0 0h512v512H0z"/>';
const PATH = /<path[^>]*\bd="([^"]+)"/g;
const tenths = (d) => d.replace(/(\.\d)\d+/g, '$1');
// the repo's folders are its authors: 'carl-olsen' → 'Carl Olsen'
const author = (folder) => folder.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');

// icons: { key: '<author>/<name>' }; out: a path from the repo root; prefix: 'KILLICON' → KILLICON_BOX, ...;
// what: the credit's noun ('Kill icons'); script: the generator's path, for the header
export async function bakeIcons({ icons, out, prefix, what, script }) {
  const baked = {};
  const used = new Set();
  for (const [key, src] of Object.entries(icons)) {
    const res = await fetch(`${REPO}/${COMMIT}/${src}.svg`);
    if (!res.ok) throw new Error(`${src}: HTTP ${res.status}`);
    const svg = (await res.text()).replace(BACKGROUND, '');
    const paths = [...svg.matchAll(PATH)].map((m) => tenths(m[1]));
    if (!paths.length) throw new Error(`${src}: no path`);
    const by = author(src.split('/')[0]);
    used.add(by);
    baked[key] = { d: paths.join(' '), by, src };
  }
  const by = [...used].sort();
  const names = by.length > 1 ? `${by.slice(0, -1).join(', ')} and ${by.at(-1)}` : by[0];
  const credit = `${what} by ${names}, from game-icons.net (CC BY 3.0, recoloured)`;
  const body = Object.entries(baked).map(([k, v]) => `  ${/^[A-Za-z_]\w*$/.test(k) ? k : `'${k}'`}: { by: '${v.by}', src: '${v.src}', d: '${v.d}' },`).join('\n');
  const file = join(ROOT, out);
  writeFileSync(file, `// Generated by ${script}: don't edit, rerun it.
// game-icons.net icons (https://game-icons.net, CC BY 3.0: https://creativecommons.org/licenses/by/3.0/),
// commit ${COMMIT} of github.com/game-icons/icons. Changes: the black background
// square removed, numbers cut to one decimal, drawn in one colour.
// Each: d (path data in a 512-unit box), by (its author), src (its file in the repo).
export const ${prefix}_BOX = 512;
export const ${prefix}_CREDIT = '${credit}';
export const ${prefix}S = {
${body}
};
`);
  console.log(`${Object.keys(baked).length} icons → ${relative(ROOT, file)} (${(body.length / 1024).toFixed(1)} KB)\n${credit}`);
}
