// Build-time scalar kernel emission. Runtime never reflects minified JS source.
import { readFileSync, writeFileSync } from 'node:fs';
import { CONTACT_KERNEL } from '../../src/v2/contact.js';
import { ctContactClosed, ctContactLife } from '../../src/electricity.js';
import { emitContactKernel } from '../../src/shaders/v2/contact.js';
const code = CONTACT_KERNEL.map(([fn, args, result]) => emitContactKernel(fn, args, result)).join('\n');
const artifact = '// Generated by node tools/v2/contact-kernel.mjs --write. Do not edit.\nexport const contactKernelWGSL = ' + JSON.stringify(code) + ';\n';
const path = new URL('../../src/shaders/v2/contact-kernel.js', import.meta.url);
if (process.argv.includes('--write')) writeFileSync(path, artifact);
else if (readFileSync(path, 'utf8') !== artifact) throw Error('Stale contact WGSL: node tools/v2/contact-kernel.mjs --write');
const contacts = [[ctContactClosed, ['i32', 'f32'], 'bool'], [ctContactLife, ['i32', 'f32', 'bool'], 'f32']]
  .map(([fn, args, result]) => emitContactKernel(fn, args, result)).join('\n').replace(/\bCT_CONTACTOR_HOLD\b/g, 'CONTACTOR_HOLD').replace(/\bCT_/g, 'E_')
  .replace(/\bctContactClosed\b/g, 'electricContactClosed').replace(/\bctContactLife\b/g, 'electricContactLife');
const contactArtifact = '// Generated by node tools/v2/contact-kernel.mjs --write. Do not edit.\nexport const electricContactKernelWGSL = ' + JSON.stringify(contacts) + ';\n';
const contactPath = new URL('../../src/shaders/electric-contact-kernel.js', import.meta.url);
if (process.argv.includes('--write')) writeFileSync(contactPath, contactArtifact);
else if (readFileSync(contactPath, 'utf8') !== contactArtifact) throw Error('Stale electrical contact WGSL: node tools/v2/contact-kernel.mjs --write');
console.log('Native contact scalar WGSL matches CPU source');
