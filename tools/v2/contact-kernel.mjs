// Build-time scalar kernel emission. Runtime never reflects minified JS source.
import { readFileSync, writeFileSync } from 'node:fs';
import { CONTACT_KERNEL } from '../../src/v2/contact.js';
import { emitContactKernel } from '../../src/shaders/v2/contact.js';
const code = CONTACT_KERNEL.map(([fn, args, result]) => emitContactKernel(fn, args, result)).join('\n');
const artifact = '// Generated by node tools/v2/contact-kernel.mjs --write. Do not edit.\nexport const contactKernelWGSL = ' + JSON.stringify(code) + ';\n';
const path = new URL('../../src/shaders/v2/contact-kernel.js', import.meta.url);
if (process.argv.includes('--write')) writeFileSync(path, artifact);
else if (readFileSync(path, 'utf8') !== artifact) throw Error('Stale contact WGSL: node tools/v2/contact-kernel.mjs --write');
console.log('Native contact scalar WGSL matches CPU source');
