// The start menu's map previews (public/maps/<key>.webp): every map in
// src/maps.js, rendered by the app itself from its home view, square, the way
// Garry's Mod shows a map before you load it. Rerun after changing a map, on
// a real GPU: the previews are the game's own view at its own window.
// usage: node tools/map-thumbs.mjs [--port 5733] [--only key,key] [--out dir] [--quick] [--views [--views-out dir]]
// --views: the Shaders menu's previews too (public/views/<key>/<view>.webp), from the same
// shot's camera, drawn by the menu's own renderer (__app.renderThumb); then raise the map's
// viewPreviewVersion in src/maps.js so browsers fetch the new ones.
// Runs its own Vite (tools/vite-server.mjs; --port: on that port).
// --quick (the container's SwiftShader, docs/webgpu.md I1): a world's window
// 64 wide (?win=64) in the plain view (?view=plain), and the far field not
// waited out (its whole build is minutes there; the plain view doesn't draw
// it anyway), and the shot is one frame (test.renderOnce), not a converged
// one: a check that the tool runs, not previews to commit, so they go to
// /tmp/map-thumbs unless --out says where.
// Tinker Creek's full cold boot can exceed a GPU slot. Its bounded Cozy-artwork
// preview is generated by tools/willow-cozy-thumb.mjs from the current scene.
import { launchBrowser, newTestPage, ready, render } from './browser.mjs';
import { startVite } from './vite-server.mjs';
import { mkdirSync, writeFileSync } from 'fs';
import { execFileSync } from 'child_process';
import { join } from 'path';
import { MAPS, isWorld } from '../src/maps.js';
import { VIEWS, THUMB_SIZE } from '../src/views.js';
import assert from 'node:assert/strict';

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : d; };
const port = Number(opt('port', '5733'));
const only = (opt('only', '') ?? '').split(',').filter(Boolean);
const QUICK = args.includes('--quick');
const OUT = opt('out', QUICK ? '/tmp/map-thumbs' : join(new URL('..', import.meta.url).pathname, 'public/maps'));
const VIEW_SHOTS = args.includes('--views');
const VIEWS_OUT = opt('views-out', QUICK ? '/tmp/view-thumbs' : join(new URL('..', import.meta.url).pathname, 'public/views'));

const RENDER = 900;          // px: the square the app renders
const SIZE = 400;            // px: the preview (a menu card is ~150 px, twice that on a retina screen)
const QUALITY = 80;          // webp quality
const VIEW_TRIES = 40;       // renderThumb attempts per view (Plain's blocks renderer starts after its switch)
const VIEW_RETRY_MS = 250;   // ms between them
const SUN = { az: 35, el: 32 };   // degrees: a warm afternoon light on every map
const STEPS = 90;            // simulation steps before the shot: lava glows, sand starts to fall
const LOAD_TIMEOUT = 180000; // ms: a cold shader compile plus a world's far field
// per map: the home view pulled in or out (× its distance to the target)
const ZOOM = { damValley: 0.72, willowCove: 6.5 };
// Show the expanded town, northern city and neighborhoods, not only the old core.
const TARGET = { willowCove: [-160, 24, -100] };

// ImageMagick 7's `magick`, else 6's `convert` (the same arguments)
function toWebp(png, file) {
  const argv = ['png:-', '-resize', `${SIZE}x${SIZE}`, '-quality', String(QUALITY), file];
  try {
    execFileSync('magick', argv, { input: png });
  } catch (e) {
    if (e.code !== 'ENOENT') throw e;
    execFileSync('convert', argv, { input: png });
  }
}

mkdirSync(OUT, { recursive: true });
const vite = await startVite({ port });
let browser;
const errs = [];
try {
  browser = await launchBrowser();
  for (const m of MAPS.filter((x) => !only.length || only.includes(x.key))) {
    const p = await newTestPage(browser, { mode: 'ui', viewport: { width: RENDER, height: RENDER } });
    try {
      p.on('pageerror', (e) => errs.push(`${m.key}: ${String(e).slice(0, 300)}`));
      // (the relay the UI asks for quota isn't running here)
      p.on('console', (msg) => { if (msg.type() === 'error' && !msg.text().includes('ERR_CONNECTION_REFUSED')) errs.push(`${m.key}: ${msg.text().slice(0, 300)}`); });
      await p.addInitScript(() => addEventListener('DOMContentLoaded', () => {
        const st = document.createElement('style');
        st.textContent = 'body * { visibility: hidden !important; } #app > canvas { visibility: visible !important; }';
        document.head.appendChild(st);
      }));
      const t0 = Date.now();
      await p.goto(vite.url(`/?map=${m.key}${QUICK ? '&win=64&view=plain' : m.key === 'willowCove' ? '&view=cozy' : ''}`), { timeout: LOAD_TIMEOUT });
      await ready(p);
      if (m.key === 'willowCove' && !QUICK)
        assert.equal(await p.evaluate(() => __app.settings.view), VIEWS.find(v => v.key === 'cozy').id, 'Tinker Creek preview must use Cozy');
      console.log(`${m.key}: app ready after ${((Date.now() - t0) / 1000).toFixed(1)} s`);
      // Keep callbacks live until the world's far field has finished filling in.
      if (isWorld(m)) {
        await p.waitForFunction((quick) => window.__app.win?.loaded && window.__app.win.far.ready && (quick || !window.__app.win.far.queue.length),
          QUICK, { timeout: LOAD_TIMEOUT, polling: 500 });
        console.log(`${m.key}: world ready after ${((Date.now() - t0) / 1000).toFixed(1)} s`);
      }
      await p.evaluate(async ([sun, steps, zoom, target]) => {
        const a = window.__app;
        a.test.park();
        await a.test.ready();   // (the grid's pipelines: test.step needs them built)
        a.autoRes.enabled = false;
        a.renderer.setPixelRatio(1);
        a.renderer.setSize(innerWidth, innerHeight);
        dispatchEvent(new Event('resize'));
        a.day.fixed = sun;
        a.settings.paused = true;
        a.test.step(steps);
        a.rig.reset(true);
        if (target) {
          const absolute = new a.THREE.Vector3(a.win.P.size[0] / 2 + target[0], target[1], a.win.P.size[2] / 2 + target[2]);
          const framed = absolute.sub(a.sim.origin).multiplyScalar(a.scale).add(a.volume.position);
          a.camera.position.add(framed.clone().sub(a.controls.target));
          a.controls.target.copy(framed);
        }
        a.camera.position.sub(a.controls.target).multiplyScalar(zoom).add(a.controls.target);
        a.controls.update();
        a.post.reset();
      }, [SUN, STEPS, ZOOM[m.key] ?? 1, TARGET[m.key]]);
      if (QUICK) await p.evaluate(() => window.__app.test.renderOnce());
      else await render(p);
      const png = await p.screenshot({ type: 'png' });
      toWebp(png, join(OUT, `${m.key}.webp`));
      console.log(`${m.key}: ${((Date.now() - t0) / 1000).toFixed(1)} s → ${join(OUT, `${m.key}.webp`)}`);
      if (VIEW_SHOTS) {
        const shots = await p.evaluate(async ([views, size, quality, tries, retryMs]) => {
          const a = window.__app, start = a.settings.view, out = {};
          a.test.resume();
          try {
            for (const v of views) {   // (Plain last: from another view its card needs Plain on: app.js renderThumb)
              if (v.key === 'plain') a.setView(v.id);
              const c = document.createElement('canvas');
              [c.width, c.height] = size;
              let ok = false;
              for (let i = 0; !ok && i < tries; i++) {
                ok = await a.renderThumb(v.id, c);
                if (!ok) await new Promise((r) => setTimeout(r, retryMs));
              }
              if (ok) out[v.key] = c.toDataURL('image/webp', quality / 100);
            }
          } finally {
            a.setView(start);
            a.test.park();
          }
          return out;
        }, [VIEWS.map(({ id, key }) => ({ id, key })), THUMB_SIZE, QUALITY, VIEW_TRIES, VIEW_RETRY_MS]);
        const dir = join(VIEWS_OUT, m.key);
        mkdirSync(dir, { recursive: true });
        for (const [view, url] of Object.entries(shots)) writeFileSync(join(dir, `${view}.webp`), Buffer.from(url.split(',')[1], 'base64'));
        const missing = VIEWS.filter((v) => !shots[v.key]).map((v) => v.key);
        if (missing.length) errs.push(`${m.key}: no view preview for ${missing.join(', ')}`);
        console.log(`${m.key}: ${Object.keys(shots).length} view previews → ${dir}`);
      }
    } finally {
      await p.close();
    }
  }
  console.log(errs.length ? errs.join('\n') : 'no errors');
} finally {
  await browser?.close();
  await vite.close();
}
